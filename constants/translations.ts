const dictionaries: Record<Language, TranslationTree> = { my, en };

function resolvePath(tree: TranslationTree, key: string): string | undefined {
  const value = key.split('.').reduce<string | TranslationTree | undefined>((acc, part) => {
    if (acc && typeof acc === 'object') {
      return acc[part];
    }
    return undefined;
  }, tree);

  return typeof value === 'string' ? value : undefined;
}

function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) {
    return template;
  }

  return template.replace(/\{(\w+)\}/g, (match, name) =>
    name in params ? String(params[name]) : match,
  );
}

export function translate(
  language: Language,
  key: string,
  params?: Record<string, string | number>,
): string {
  const resolved =
    resolvePath(dictionaries[language], key) ??
    resolvePath(dictionaries[DEFAULT_LANGUAGE], key) ??
    resolvePath(dictionaries.en, key);

  if (resolved === undefined) {
    return key;
  }

  return interpolate(resolved, params);
}
